"""The vault: plain markdown files Bonnington keeps, sorted into Academic, Personal and Projects.

Source files hold one item per line in a strict format and are the user's to edit. Lines that don't
parse are left untouched. Calendar.md and Academic/Subjects/*.md are generated from the source files.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date, time
from pathlib import Path

GENERATED = "_Generated by Bonnington. Edits here are overwritten._"


class NotFound(Exception):
    pass


class Ambiguous(Exception):
    pass


def _num(x: float) -> str:
    return f"{x:g}"


@dataclass
class Exam:
    subject: str
    on: date
    at: time | None = None
    title: str = "Exam"
    note: str = ""
    done: bool = False
    kind = "exam"

    def line(self) -> str:
        when = self.on.isoformat() + (f" {self.at:%H:%M}" if self.at else "")
        parts = [when, self.subject, self.title] + ([self.note] if self.note else [])
        return f"- [{'x' if self.done else ' '}] " + " | ".join(parts)

    def text(self) -> str:
        return f"{self.subject} {self.title} {self.note}"

    def describe(self) -> str:
        when = self.on.isoformat() + (f" {self.at:%H:%M}" if self.at else "")
        return f"{self.subject} {self.title} on {when}"


@dataclass
class Assignment:
    subject: str
    title: str
    due: date
    done: bool = False
    kind = "assignment"

    def line(self) -> str:
        return f"- [{'x' if self.done else ' '}] {self.due.isoformat()} | {self.subject} | {self.title}"

    def text(self) -> str:
        return f"{self.subject} {self.title}"

    def describe(self) -> str:
        return f"{self.subject} {self.title} due {self.due.isoformat()}"


@dataclass
class Task:
    title: str
    due: date | None = None
    done: bool = False
    kind = "task"

    def line(self) -> str:
        due = f" | due {self.due.isoformat()}" if self.due else ""
        return f"- [{'x' if self.done else ' '}] {self.title}{due}"

    def text(self) -> str:
        return self.title

    def describe(self) -> str:
        return self.title + (f" due {self.due.isoformat()}" if self.due else "")


@dataclass
class Score:
    subject: str
    exam: str
    score: float
    out_of: float
    on: date
    done: bool = False
    kind = "score"

    def line(self) -> str:
        return f"- {self.on.isoformat()} | {self.subject} | {self.exam} | {_num(self.score)}/{_num(self.out_of)}"

    def text(self) -> str:
        return f"{self.subject} {self.exam}"

    def describe(self) -> str:
        return f"{self.subject} {self.exam}: {_num(self.score)}/{_num(self.out_of)}"

    @property
    def percent(self) -> int:
        return round(100 * self.score / self.out_of) if self.out_of else 0


_BOX = r"- \[( |x|X)\] "
_DATE = r"(\d{4}-\d{2}-\d{2})"


def _parse_exam(line: str) -> Exam | None:
    m = re.fullmatch(_BOX + _DATE + r"(?: (\d{2}):(\d{2}))? \| ([^|]+?) \| ([^|]+?)(?: \| (.*))?", line.strip())
    if not m:
        return None
    try:
        at = time(int(m[3]), int(m[4])) if m[3] else None
        return Exam(m[5].strip(), date.fromisoformat(m[2]), at, m[6].strip(), (m[7] or "").strip(), m[1] != " ")
    except ValueError:
        return None


def _parse_assignment(line: str) -> Assignment | None:
    m = re.fullmatch(_BOX + _DATE + r" \| ([^|]+?) \| (.+)", line.strip())
    if not m:
        return None
    try:
        return Assignment(m[3].strip(), m[4].strip(), date.fromisoformat(m[2]), m[1] != " ")
    except ValueError:
        return None


def _parse_task(line: str) -> Task | None:
    m = re.fullmatch(_BOX + r"(.+?)(?: \| due " + _DATE + r")?", line.strip())
    if not m:
        return None
    try:
        return Task(m[2].strip(), date.fromisoformat(m[3]) if m[3] else None, m[1] != " ")
    except ValueError:
        return None


def _parse_score(line: str) -> Score | None:
    m = re.fullmatch(r"- " + _DATE + r" \| ([^|]+?) \| ([^|]+?) \| ([\d.]+)/([\d.]+)", line.strip())
    if not m:
        return None
    try:
        return Score(m[2].strip(), m[3].strip(), float(m[4]), float(m[5]), date.fromisoformat(m[1]))
    except ValueError:
        return None


_KINDS = {
    "exam": ("Academic/Exams.md", "Exams", _parse_exam),
    "assignment": ("Academic/Assignments.md", "Assignments", _parse_assignment),
    "task": ("Personal/Tasks.md", "Tasks", _parse_task),
    "score": ("Academic/Scores.md", "Scores", _parse_score),
}


class Vault:
    def __init__(self, root: Path) -> None:
        self.root = Path(root)
        self._undo: tuple[str, dict[Path, str | None]] | None = None

    # --- reading ------------------------------------------------------------------
    def _path(self, kind: str) -> Path:
        return self.root / _KINDS[kind][0]

    def _lines(self, kind: str) -> list[str]:
        p = self._path(kind)
        return p.read_text(encoding="utf-8").splitlines() if p.exists() else [f"# {_KINDS[kind][1]}", ""]

    def _items(self, kind: str) -> list[tuple[int, object]]:
        parse = _KINDS[kind][2]
        return [(i, item) for i, line in enumerate(self._lines(kind)) if (item := parse(line)) is not None]

    def exams(self) -> list[Exam]:
        return [it for _, it in self._items("exam")]

    def assignments(self) -> list[Assignment]:
        return [it for _, it in self._items("assignment")]

    def tasks(self) -> list[Task]:
        return [it for _, it in self._items("task")]

    def scores(self) -> list[Score]:
        return [it for _, it in self._items("score")]

    def subjects(self) -> list[str]:
        seen: dict[str, str] = {}
        for it in [*self.exams(), *self.assignments(), *self.scores()]:
            seen.setdefault(it.subject.lower(), it.subject)
        return list(seen.values())

    def _subject(self, name: str) -> str:
        name = name.strip()
        return next((s for s in self.subjects() if s.lower() == name.lower()), name)

    # --- writing ------------------------------------------------------------------
    def _begin(self, description: str, kinds: list[str]) -> None:
        snap = {}
        for k in kinds:
            p = self._path(k)
            snap[p] = p.read_text(encoding="utf-8") if p.exists() else None
        self._undo = (description, snap)

    def _write(self, kind: str, lines: list[str]) -> None:
        p = self._path(kind)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")

    def _append(self, item) -> None:
        self._begin(f"added {item.kind}: {item.describe()}", [item.kind])
        self._write(item.kind, self._lines(item.kind) + [item.line()])
        self.regenerate()

    def add_exam(self, subject: str, on: date, at: time | None = None, title: str = "Exam", note: str = "") -> Exam:
        exam = Exam(self._subject(subject), on, at, (title or "Exam").strip(), (note or "").strip())
        self._append(exam)
        return exam

    def add_assignment(self, subject: str, title: str, due: date) -> Assignment:
        a = Assignment(self._subject(subject), title.strip(), due)
        self._append(a)
        return a

    def add_task(self, title: str, due: date | None = None) -> Task:
        t = Task(title.strip(), due)
        self._append(t)
        return t

    def add_score(self, subject: str, exam: str, score: float, out_of: float, on: date) -> Score:
        s = Score(self._subject(subject), exam.strip(), score, out_of, on)
        self._append(s)
        return s

    def _find(self, kind: str, query: str, include_done: bool) -> tuple[int, object]:
        if kind not in _KINDS:
            raise NotFound(f"unknown kind {kind!r}")
        words = re.findall(r"\w+", query.lower())
        hits = [(i, it) for i, it in self._items(kind)
                if (include_done or not it.done) and all(w in it.text().lower() for w in words)]
        if not hits:
            raise NotFound(f"no {kind} matching {query!r}")
        if len(hits) > 1:
            exact = [h for h in hits if h[1].text().strip().lower() == query.strip().lower()]
            if len(exact) == 1:
                return exact[0]
            raise Ambiguous(f"several {kind}s match {query!r}: " + "; ".join(it.describe() for _, it in hits))
        return hits[0]

    def mark_done(self, kind: str, query: str):
        i, item = self._find(kind, query, include_done=False)
        self._begin(f"marked {kind} done: {item.describe()}", [kind])
        item.done = True
        lines = self._lines(kind)
        lines[i] = item.line()
        self._write(kind, lines)
        self.regenerate()
        return item

    def remove(self, kind: str, query: str):
        i, item = self._find(kind, query, include_done=True)
        self._begin(f"removed {kind}: {item.describe()}", [kind])
        lines = self._lines(kind)
        del lines[i]
        self._write(kind, lines)
        self.regenerate()
        return item

    def undo(self) -> str | None:
        """Take back the last change. Returns what was undone, or None if there is nothing to undo."""
        if self._undo is None:
            return None
        description, snap = self._undo
        self._undo = None
        for p, text in snap.items():
            if text is None:
                p.unlink(missing_ok=True)
            else:
                p.write_text(text, encoding="utf-8")
        self.regenerate()
        return description

    # --- generated files -------------------------------------------------------------
    def dated(self) -> list[tuple[date, time | None, str, str]]:
        """Every open dated item as (date, time, label, text), soonest first."""
        rows: list[tuple[date, time | None, str, str]] = []
        rows += [(e.on, e.at, "Exam", f"{e.subject}: {e.title}") for e in self.exams() if not e.done]
        rows += [(a.due, None, "Assignment", f"{a.subject}: {a.title}") for a in self.assignments() if not a.done]
        rows += [(t.due, None, "Task", t.title) for t in self.tasks() if not t.done and t.due]
        return sorted(rows, key=lambda r: (r[0], r[1] or time(0, 0), r[2], r[3]))

    def regenerate(self) -> None:
        self.root.mkdir(parents=True, exist_ok=True)
        cal = ["# Calendar", "", GENERATED, ""]
        for on, at, label, text in self.dated():
            cal.append(f"- {on.isoformat()}{f' {at:%H:%M}' if at else ''} | {label} | {text}")
        (self.root / "Calendar.md").write_text("\n".join(cal) + "\n", encoding="utf-8")

        folder = self.root / "Academic" / "Subjects"
        folder.mkdir(parents=True, exist_ok=True)
        wanted = set()
        for subject in self.subjects():
            name = re.sub(r'[\\/:*?"<>|]', "_", subject) + ".md"
            wanted.add(name)
            (folder / name).write_text(self.subject_gist(subject), encoding="utf-8")
        for stale in folder.glob("*.md"):
            if stale.name not in wanted:
                stale.unlink()

    def subject_gist(self, subject: str) -> str:
        key = subject.lower()
        out = [f"# {subject}", "", GENERATED, "", "## Coming up"]
        coming = [(e.on, f"- {e.on.isoformat()}{f' {e.at:%H:%M}' if e.at else ''} Exam: {e.title}"
                   + (f" ({e.note})" if e.note else ""))
                  for e in self.exams() if e.subject.lower() == key and not e.done]
        coming += [(a.due, f"- {a.due.isoformat()} Assignment: {a.title}")
                   for a in self.assignments() if a.subject.lower() == key and not a.done]
        out += [line for _, line in sorted(coming)] or ["- nothing recorded"]
        scores = sorted((s for s in self.scores() if s.subject.lower() == key), key=lambda s: s.on, reverse=True)
        out += ["", "## Scores"]
        out += [f"- {s.on.isoformat()} {s.exam}: {_num(s.score)}/{_num(s.out_of)} ({s.percent}%)" for s in scores] \
            or ["- none yet"]
        total = sum(s.out_of for s in scores)
        if total:
            out += ["", f"Average: {round(100 * sum(s.score for s in scores) / total)}%"]
        return "\n".join(out) + "\n"
